import fs from 'node:fs'; import os from 'node:os'; import path from 'node:path'; import { spawn } from 'node:child_process'
import { createRequire } from 'node:module'
const require = createRequire(import.meta.url)
const { chromium } = require('playwright-core')
const CDP = 10030
const EDGE=['C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe','C:/Program Files/Microsoft/Edge/Application/msedge.exe'].find(c=>fs.existsSync(c))
const child=spawn(EDGE,[`--remote-debugging-port=${CDP}`,`--user-data-dir=${path.join(os.tmpdir(),'resize-'+Date.now())}`,'--no-first-run','--headless=new','--window-size=1400,900','about:blank'],{stdio:'ignore'})
let ready=false; const t0=Date.now()
while(Date.now()-t0<20000&&!ready){ try{ ready=(await fetch(`http://127.0.0.1:${CDP}/json/version`)).ok }catch{}; if(!ready) await new Promise(r=>setTimeout(r,200)) }
const browser=await chromium.connectOverCDP(`http://127.0.0.1:${CDP}`)
const page=await browser.contexts()[0].newPage()
await page.goto('http://127.0.0.1:8793/demo/index.html?demo=1')
await page.waitForTimeout(1200)
await page.evaluate(() => { localStorage.setItem('dsh.talk-map.status-rail.open.v1','1'); localStorage.removeItem('dsh.talk-map.status-rail.width.v1') })
await page.reload(); await page.waitForTimeout(2600)
const widthOf = () => page.evaluate(() => Math.round(document.querySelector('[class*="statusRailPanel"]').getBoundingClientRect().width))
const before = await widthOf()
const tab = await page.evaluate(() => { const r=document.querySelector('[class*="statusRailTab"]').getBoundingClientRect(); return {x:Math.round(r.x+r.width/2), y:Math.round(r.y+r.height/2)} })
await page.mouse.move(tab.x, tab.y)
await page.mouse.down()
for (const dx of [20, 60, 120]) { await page.mouse.move(tab.x + dx, tab.y); await page.waitForTimeout(60) }
await page.mouse.up()
await page.waitForTimeout(300)
const after = await widthOf()
const stored = await page.evaluate(() => localStorage.getItem('dsh.talk-map.status-rail.width.v1'))
const stillOpen = await page.evaluate(() => document.querySelector('[class*="statusRail"]')?.getAttribute('data-open'))
await page.reload(); await page.waitForTimeout(2400)
const persisted = await widthOf()
console.log(JSON.stringify({ before, after, stored, stillOpen, persisted }))
await page.screenshot({ path: 'test/shots/rail-resized.png', clip: { x: 30, y: 40, width: 640, height: 760 } })
await page.close(); await browser.close(); child.kill()
